"""The 5B filter experiment and its 10B follow-on. 5B: five arms (control = 5B prefix pool of the trained longmino
corpus; filtered_k2 = the term screen's K=2 survivors; mixmatch = unfiltered text at the
filtered arm's family proportions, the control for the mix shift the screen causes; and a
second replicate of the last two on documents disjoint from the first), each one job of 298
iterations that
never resumes, saving every 30 iterations so checkpoints exist at 30 / 90 / 298 (0.5 / 1.5 /
5.0B tokens, log-spaced; the others are deleted after the run). Each config is the 20B
longmino config with exactly the stated keys changed. Generated by make_5b_configs.py; these
tests pin what it must produce. 10B (--budget 10b): every arm at the K=2 filtered arm's
family mix — a mix-matched control and two K=1 replicates sharing one pool of the K=1
survivors of two corpus slices (1.76 passes), 596 iterations, saves kept at 60 / 180 / 596.
"""

