"""Write the cooldown branches of a campaign's arms from its cooldown spec.

A cooldown branch resumes an arm's save at a branch point. It decays the learning rate to the arm's ``min_lr`` over a
fixed number of samples with Megatron's WSD schedule. It then saves and exits. It keeps the arm's dataset
(``train.train_iters``) and resumes at the arm's consumed samples. It therefore reads on through the arm's own token
stream. The recipe's ``scheduler.override_opt_param_scheduler`` replaces the schedule that the save holds with the
branch's.

The spec (``cooldowns.yaml``) is the only input that decides the branches::

    arms: [<arm config beside the spec>, ...]
    branches:
      - {name: <name>, at_samples: <samples the arm reads before the branch point>, decay_samples: <samples>}
    decay_style: <a WSD decay style, such as minus_sqrt>

Each branch point must be a save of the arm, a multiple of ``checkpoint.save_interval``, at or before
``train.exit_interval``. Both sample counts must be whole iterations of the arm's batch. The script writes branch
``<name>`` of ``<stem>_<stage>.yaml`` beside the spec as ``<stem>_<name>_<stage>.yaml``. The branch saves to the
arm's save directory with ``_<name>`` appended. Its W&B run is the arm's with ``_<name>`` appended. A test
regenerates the branches and compares them with the files.

    python configs/control_pretraining/generate_cooldown_branches.py <cooldowns.yaml>
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml


REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))
from scripts.mapping_keys import require_keys, require_whole_number  # noqa: E402
from scripts.training.config_compose import load_composed_yaml  # noqa: E402


SPEC_KEYS = frozenset({"arms", "branches", "decay_style"})
BRANCH_KEYS = frozenset({"name", "at_samples", "decay_samples"})
HEADER = "# Generated by configs/control_pretraining/generate_cooldown_branches.py from {spec}. Do not edit.\n"


@dataclass(frozen=True)
class Branch:
    """One branch point of the spec: the branch's name, the samples the arm reads before it, and the decay's length."""

    name: str
    at_samples: int
    decay_samples: int


@dataclass(frozen=True)
class CooldownSpec:
    """A parsed cooldown spec (see the module docstring)."""

    path: Path
    arms: tuple[Path, ...]
    branches: tuple[Branch, ...]
    decay_style: str


def read_spec(path: Path) -> CooldownSpec:
    """Parse a cooldown spec, refusing unknown and missing keys, an arm config that is not beside it, and two branches
    of one name."""
    loaded = require_keys(yaml.safe_load(path.read_text()), f"{path}", SPEC_KEYS)
    arms = tuple(path.parent / str(arm) for arm in loaded["arms"])
    missing = [str(arm) for arm in arms if not arm.is_file()]
    if missing:
        raise ValueError(f"{path}: arms names configs that are not beside it: {missing}")
    branches = []
    for index, entry in enumerate(loaded["branches"]):
        where = f"{path}: branches[{index}]"
        entry = require_keys(entry, where, BRANCH_KEYS)
        branches.append(
            Branch(
                name=str(entry["name"]),
                at_samples=require_whole_number(entry["at_samples"], f"{where}.at_samples", 1),
                decay_samples=require_whole_number(entry["decay_samples"], f"{where}.decay_samples", 1),
            )
        )
    names = [branch.name for branch in branches]
    if len(set(names)) != len(names):
        raise ValueError(f"{path}: two branches share a name: {names}")
    return CooldownSpec(path, arms, tuple(branches), str(loaded["decay_style"]))


def branch_path(arm: Path, branch: Branch) -> Path:
    """Where branch ``branch`` of the arm config ``arm`` (``<stem>_<stage>.yaml``) is written."""
    stem, stage = arm.stem.rsplit("_", 1)
    return arm.with_name(f"{stem}_{branch.name}_{stage}.yaml")


def _iterations(samples: int, batch: int, where: str) -> int:
    if samples % batch:
        raise ValueError(f"{where}: {samples} samples are not whole iterations of the global batch, {batch}")
    return samples // batch


def branch_config(spec: CooldownSpec, arm: Path, branch: Branch) -> dict:
    """The settings branch ``branch`` of ``arm`` states on top of the arm config.

    Raises:
        ValueError: when a sample count is not whole iterations of the arm's batch, the branch point is no save of
            the arm or lies past its exit, or the decay ends past the arm's ``train_iters``.
    """
    composed = load_composed_yaml(str(arm))
    train, checkpoint = composed["train"], composed["checkpoint"]
    where = f"{spec.path}: branch {branch.name} of {arm.name}"
    batch = train["global_batch_size"]
    start = _iterations(branch.at_samples, batch, where)
    decay = _iterations(branch.decay_samples, batch, where)
    if start % checkpoint["save_interval"] or start > train["exit_interval"]:
        raise ValueError(
            f"{where}: iteration {start} is not a save before the arm exits (every {checkpoint['save_interval']} "
            f"iterations up to {train['exit_interval']})"
        )
    if start + decay > train["train_iters"]:
        raise ValueError(
            f"{where}: the decay ends at iteration {start + decay}, past train_iters {train['train_iters']}"
        )
    save = Path(checkpoint["save"])
    return {
        "base_config": arm.name,
        "train": {"exit_interval": start + decay},
        "scheduler": {
            "lr_decay_style": "WSD",
            "lr_wsd_decay_style": spec.decay_style,
            "lr_decay_iters": start + decay,
            "lr_wsd_decay_iters": decay,
        },
        "checkpoint": {
            "load": str(save),
            "ckpt_step": start,
            "save": str(save.with_name(f"{save.name}_{branch.name}")),
        },
        "logger": {"wandb_exp_name": f"{composed['logger']['wandb_exp_name']}_{branch.name}"},
    }


def render(spec: CooldownSpec) -> dict[Path, str]:
    """The text of every branch config of the spec, keyed by its path."""
    rendered = {}
    for arm in spec.arms:
        for branch in spec.branches:
            settings = branch_config(spec, arm, branch)
            text = HEADER.format(spec=spec.path.name) + yaml.safe_dump(settings, sort_keys=False)
            rendered[branch_path(arm, branch)] = text
    return rendered


def main(argv: list[str] | None = None) -> int:
    """Write the branch configs of a cooldown spec beside it."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("spec", type=Path, help="the cooldown spec")
    args = parser.parse_args(argv)
    for path, text in render(read_spec(args.spec.resolve())).items():
        path.write_text(text)
        print(path.relative_to(REPO_ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
